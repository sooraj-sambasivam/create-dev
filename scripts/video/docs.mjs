#!/usr/bin/env node
// Renders docs/pitch/video-script.md from beats.mjs (the narration is read from the same data the voice step uses).
import fs from "node:fs";
import path from "node:path";
import { BEATS } from "./beats.mjs";
import { REPO } from "./lib.mjs";

const words = (s) => s.trim().split(/\s+/).length;
let out = `# Create: demo video voiceover and shot plan

Generated by scripts/video/docs.mjs from scripts/video/beats.mjs. Do not edit by hand.

Content is the canonical demo set (scripts/eval/demo/demo-set.json): L02 lift of the sales spreadsheet, C01 chat, E01 "make this bigger", B02 study-night sign-up. Voice: ElevenLabs default voice George (JBFqnCBsd6RMkjVDRZzb). Draft: \`pnpm video:draft\`. Total narration: ${BEATS.reduce((n, b) => n + words(b.narration), 0)} words.

| # | Beat | Sponsor shown | Caption |
| --- | --- | --- | --- |
${BEATS.map((b, i) => `| ${i + 1} | ${b.id} | ${b.sponsor || "-"} | ${b.caption} |`).join("\n")}
`;
for (const b of BEATS) {
  out += `\n## ${b.id}${b.scenario ? ` (${b.scenario})` : ""}\n\n**Narration (${words(b.narration)} words):** ${b.narration}\n\n**Caption:** ${b.caption}\n\n**Steps:**\n${b.steps.map((s) => `- ${s}`).join("\n")}\n`;
}
fs.writeFileSync(path.join(REPO, "docs/pitch/video-script.md"), out);
console.log("wrote docs/pitch/video-script.md");
